function makeT(lang) {
  const d = dicts[lang] || de;
  return function t(key, fallback) {
    const v = d[key];
    if (v !== undefined) return v;
    return fallback !== undefined ? fallback : (de[key] !== undefined ? de[key] : key);
  };
}

function isSupported(lang) {
  return lang === 'de' || lang === 'en';
}

